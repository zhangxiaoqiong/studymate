#!/bin/bash
# 停止前端服务

echo "=================================================="
echo "停止 Doc Explorer 前端服务"
echo "=================================================="
echo ""

# 杀死端口 5173 上的所有进程
echo "停止前端服务 (端口 5173)..."
lsof -ti:5173 | xargs kill -9 2>/dev/null && echo "✓ 前端服务已停止" || echo "✓ 没有找到运行的前端服务"

sleep 1
echo ""
echo "前端服务已关闭"
echo ""
