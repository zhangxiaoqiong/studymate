#!/bin/bash
# 停止后端服务

echo "=================================================="
echo "停止 Doc Explorer 后端服务"
echo "=================================================="
echo ""

# 杀死端口 8001 上的所有进程
echo "停止后端服务 (端口 8001)..."
lsof -ti:8001 | xargs kill -9 2>/dev/null && echo "✓ 后端服务已停止" || echo "✓ 没有找到运行的后端服务"

sleep 1
echo ""
echo "后端服务已关闭"
echo ""
